namespace BunnyTail.TextResource.Generator;

using System;
using System.Globalization;
using System.Linq;
using System.Text;

using BunnyTail.TextResource.Generator.Models;

using SourceGenerateHelper;

internal static class TextResourceSourceBuilder
{
    private const string CultureInfoType = "global::System.Globalization.CultureInfo";

    private static readonly string Version = typeof(TextResourceSourceBuilder).Assembly.GetName().Version.ToString();

    public static SourceBuilder Build(TableModel table)
    {
        var builder = new SourceBuilder();

        builder.AutoGenerated();
        builder.EnableNullable();
        builder.NewLine();

        var hasNamespace = table.Namespace.Length > 0;
        if (hasNamespace)
        {
            builder.Indent().Append("namespace ").Append(CSharpIdentifier.EscapeQualifiedName(table.Namespace)).NewLine();
            builder.BeginScope();
        }

        AppendClass(builder, table);

        if (hasNamespace)
        {
            builder.EndScope();
        }

        return builder;
    }

    // ------------------------------------------------------------
    // Class
    // ------------------------------------------------------------

    private static void AppendClass(SourceBuilder builder, TableModel table)
    {
        builder.Indent().Append("/// <summary>Text resource generated from ").Append(table.ClassName).Append(TextResourceModelBuilder.FileExtension).Append(".</summary>").NewLine();
        builder.Indent().Append("[global::System.CodeDom.Compiler.GeneratedCode(\"BunnyTail.TextResource\", \"").Append(Version).Append("\")]").NewLine();
        builder.Indent().Append(table.Accessibility).Append(" static class ").Append(CSharpIdentifier.EscapeTypeName(table.ClassName)).NewLine();
        builder.BeginScope();

        foreach (var entry in table.Entries)
        {
            AppendDocument(builder, table, entry);
            AppendMember(builder, entry);
            builder.NewLine();
        }

        AppendKeys(builder, table);
        builder.NewLine();

        if (table.Languages.Count == 0)
        {
            AppendSingleLanguageAccessors(builder, table);
        }
        else
        {
            AppendMultiLanguageAccessors(builder, table);
            builder.NewLine();
            AppendLanguage(builder, table);
        }

        builder.EndScope();
    }

    private static void AppendDocument(SourceBuilder builder, TableModel table, EntryModel entry)
    {
        if (table.Languages.Count == 0)
        {
            builder.Indent().Append("/// <summary>").Append(ToXml(entry.Texts[0].Display)).Append("</summary>").NewLine();
            return;
        }

        builder.Indent().Append("/// <summary>").NewLine();
        foreach (var text in entry.Texts)
        {
            builder.Indent().Append("/// <para>").Append(table.Languages[text.Language]).Append(": ").Append(ToXml(text.Display)).Append("</para>").NewLine();
        }

        if (entry.Comment is not null)
        {
            builder.Indent().Append("/// <para>").Append(ToXml(entry.Comment)).Append("</para>").NewLine();
        }

        builder.Indent().Append("/// </summary>").NewLine();
    }

    private static void AppendMember(SourceBuilder builder, EntryModel entry)
    {
        if (entry.Parameters.Count == 0)
        {
            builder.Indent().Append("public static string ").Append(entry.Key).Append(" =>").NewLine();
            builder.IndentLevel++;
            AppendText(builder, entry, ";");
            builder.IndentLevel--;
            return;
        }

        var parameters = entry.Parameters.Select(static x => CSharpIdentifier.Escape(x)).ToArray();

        builder.Indent().Append("public static string ").Append(entry.Key).Append('(').AppendJoin(parameters.Select(static x => $"object? {x}"), ", ").Append(") =>").NewLine();
        builder.IndentLevel++;
        builder.Indent().Append("global::System.String.Format(").NewLine();
        builder.IndentLevel++;
        builder.Indent().Append(CultureInfoType).Append(".CurrentCulture,").NewLine();
        AppendText(builder, entry, ",");
        builder.Indent().AppendJoin(parameters, ", ").Append(");").NewLine();
        builder.IndentLevel -= 2;
    }

    private static void AppendText(SourceBuilder builder, EntryModel entry, string terminator)
    {
        if (entry.Texts.Count == 1)
        {
            builder.Indent().Append(CSharpLiteral.Format(entry.Texts[0].Value)).Append(terminator).NewLine();
            return;
        }

        builder.Indent().Append("__Language.Current switch").NewLine();
        builder.BeginScope();
        for (var i = 1; i < entry.Texts.Count; i++)
        {
            builder.Indent().Append(entry.Texts[i].Language).Append(" => ").Append(CSharpLiteral.Format(entry.Texts[i].Value)).Append(',').NewLine();
        }

        builder.Indent().Append("_ => ").Append(CSharpLiteral.Format(entry.Texts[0].Value)).NewLine();
        builder.IndentLevel--;
        builder.Indent().Append('}').Append(terminator).NewLine();
    }

    private static void AppendKeys(SourceBuilder builder, TableModel table)
    {
        builder.Indent().Append("/// <summary>Gets the keys of this text resource.</summary>").NewLine();
        builder.Indent().Append("public static global::System.Collections.Generic.IReadOnlyList<string> Keys { get; } = new string[]").NewLine();
        builder.BeginScope();
        foreach (var entry in table.Entries)
        {
            builder.Indent().Append(CSharpLiteral.Format(entry.Key)).Append(',').NewLine();
        }

        builder.EndScope(true);
    }

    // ------------------------------------------------------------
    // Accessor
    // ------------------------------------------------------------

    private static void AppendSingleLanguageAccessors(SourceBuilder builder, TableModel table)
    {
        builder.Indent().Append("/// <summary>Gets the text of the key, or null if the key does not exist.</summary>").NewLine();
        builder.Indent().Append("public static string? GetText(string key) =>").NewLine();
        builder.IndentLevel++;
        AppendLookup(builder, table, 0, "key switch", ";");
        builder.IndentLevel--;
        builder.NewLine();
        builder.Indent().Append("/// <summary>Gets the text of the key, or null if the key does not exist.</summary>").NewLine();
        builder.Indent().Append("public static string? GetTextFor(string key, ").Append(CultureInfoType).Append(" culture) => GetText(key);").NewLine();
    }

    private static void AppendMultiLanguageAccessors(SourceBuilder builder, TableModel table)
    {
        builder.Indent().Append("/// <summary>Gets the text of the key in the current UI culture, or null if the key does not exist.</summary>").NewLine();
        builder.Indent().Append("public static string? GetText(string key) => __Lookup(__Language.Current, key);").NewLine();
        builder.NewLine();
        builder.Indent().Append("/// <summary>Gets the text of the key in the specified culture, or null if the key does not exist.</summary>").NewLine();
        builder.Indent().Append("public static string? GetTextFor(string key, ").Append(CultureInfoType).Append(" culture) => __Lookup(__Language.Resolve(culture), key);").NewLine();
        builder.NewLine();
        builder.Indent().Append("private static string? __Lookup(int language, string key) =>").NewLine();
        builder.IndentLevel++;
        builder.Indent().Append("language switch").NewLine();
        builder.BeginScope();
        for (var i = table.Languages.Count - 1; i > 0; i--)
        {
            AppendLookup(builder, table, i, $"{i} => key switch", ",");
        }

        AppendLookup(builder, table, 0, "_ => key switch", string.Empty);
        builder.EndScope(true);
        builder.IndentLevel--;
    }

    private static void AppendLookup(SourceBuilder builder, TableModel table, int language, string head, string terminator)
    {
        builder.Indent().Append(head).NewLine();
        builder.BeginScope();
        foreach (var entry in table.Entries)
        {
            var text = entry.Texts.FirstOrDefault(x => x.Language == language) ?? entry.Texts[0];
            builder.Indent().Append(CSharpLiteral.Format(entry.Key)).Append(" => ").Append(CSharpLiteral.Format(text.Value)).Append(',').NewLine();
        }

        builder.Indent().Append("_ => (string?)null").NewLine();
        builder.IndentLevel--;
        builder.Indent().Append('}').Append(terminator).NewLine();
    }

    // ------------------------------------------------------------
    // Language
    // ------------------------------------------------------------

    private static void AppendLanguage(SourceBuilder builder, TableModel table)
    {
        builder.Indent().Append("private static class __Language").NewLine();
        builder.BeginScope();

        builder.Indent().Append("private static CultureCache? cache;").NewLine();
        builder.NewLine();

        builder.Indent().Append("public static int Current").NewLine();
        builder.BeginScope();
        builder.Indent().Append("get").NewLine();
        builder.BeginScope();
        builder.Indent().Append("var culture = ").Append(CultureInfoType).Append(".CurrentUICulture;").NewLine();
        builder.Indent().Append("var current = cache;").NewLine();
        builder.Indent().Append("if ((current is null) || !global::System.Object.ReferenceEquals(current.Culture, culture))").NewLine();
        builder.BeginScope();
        builder.Indent().Append("current = new CultureCache(culture, Resolve(culture));").NewLine();
        builder.Indent().Append("cache = current;").NewLine();
        builder.EndScope();
        builder.NewLine();
        builder.Indent().Append("return current.LanguageIndex;").NewLine();
        builder.EndScope();
        builder.EndScope();
        builder.NewLine();

        builder.Indent().Append("public static int Resolve(").Append(CultureInfoType).Append(" culture)").NewLine();
        builder.BeginScope();
        builder.Indent().Append("for (var c = culture; c.Name.Length > 0; c = c.Parent)").NewLine();
        builder.BeginScope();
        builder.Indent().Append("var index = Find(c.Name);").NewLine();
        builder.Indent().Append("if (index >= 0)").NewLine();
        builder.BeginScope();
        builder.Indent().Append("return index;").NewLine();
        builder.EndScope();
        builder.EndScope();
        builder.NewLine();
        builder.Indent().Append("var name = culture.Name;").NewLine();
        builder.Indent().Append("for (var i = name.LastIndexOf('-'); i > 0; i = name.LastIndexOf('-', i - 1))").NewLine();
        builder.BeginScope();
        builder.Indent().Append("var index = Find(name.Substring(0, i));").NewLine();
        builder.Indent().Append("if (index >= 0)").NewLine();
        builder.BeginScope();
        builder.Indent().Append("return index;").NewLine();
        builder.EndScope();
        builder.EndScope();
        builder.NewLine();
        builder.Indent().Append("return 0;").NewLine();
        builder.EndScope();
        builder.NewLine();

        builder.Indent().Append("private static int Find(string name) =>").NewLine();
        builder.IndentLevel++;
        builder.Indent().Append("name switch").NewLine();
        builder.BeginScope();
        for (var i = 0; i < table.Languages.Count; i++)
        {
            builder.Indent().Append(CSharpLiteral.Format(table.Languages[i])).Append(" => ").Append(i).Append(',').NewLine();
        }

        builder.Indent().Append("_ => -1").NewLine();
        builder.EndScope(true);
        builder.IndentLevel--;
        builder.NewLine();

        builder.Indent().Append("private sealed class CultureCache").NewLine();
        builder.BeginScope();
        builder.Indent().Append("public CultureCache(").Append(CultureInfoType).Append(" culture, int languageIndex)").NewLine();
        builder.BeginScope();
        builder.Indent().Append("Culture = culture;").NewLine();
        builder.Indent().Append("LanguageIndex = languageIndex;").NewLine();
        builder.EndScope();
        builder.NewLine();
        builder.Indent().Append("public ").Append(CultureInfoType).Append(" Culture { get; }").NewLine();
        builder.NewLine();
        builder.Indent().Append("public int LanguageIndex { get; }").NewLine();
        builder.EndScope();

        builder.EndScope();
    }

    // ------------------------------------------------------------
    // Helper
    // ------------------------------------------------------------

    private static string ToXml(string value)
    {
        var buffer = new StringBuilder(value.Length);
        for (var i = 0; i < value.Length; i++)
        {
            var c = value[i];
            switch (c)
            {
                case '&':
                    buffer.Append("&amp;");
                    break;
                case '<':
                    buffer.Append("&lt;");
                    break;
                case '>':
                    buffer.Append("&gt;");
                    break;
                case '\t':
                    buffer.Append(c);
                    break;
                case '\r' when ((i + 1) < value.Length) && (value[i + 1] == '\n'):
                    break;
                default:
                    if (IsLineBreak(c))
                    {
                        buffer.Append("<br/>");
                    }
                    else if (!Char.IsControl(c))
                    {
                        buffer.Append(c);
                    }

                    break;
            }
        }

        return buffer.ToString();
    }

    private static bool IsLineBreak(char c) =>
        (c is '\r' or '\n' or (char)0x85) ||
        (Char.GetUnicodeCategory(c) is UnicodeCategory.LineSeparator or UnicodeCategory.ParagraphSeparator);
}
